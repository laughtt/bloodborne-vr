/* Red zone guard: run red-zone-free relocated copies of the eboot's ribbon/trail vertex builders.
 *
 * Root cause: the leaf function at eboot vaddr 0x28ceec0 (and its siblings 0x28ce7b0, 0x28cf580,
 * 0x28cfba0) writes vertices into a GPU-visible buffer while keeping live locals in the SysV
 * 128-byte red zone below rsp (e.g. [rsp-0x60], read every iteration at 0x28cf0d1). The GPU page
 * tracker write-protects those pages, and any exception on the guest thread (a tracked read or
 * write, inside or outside the output range) makes Windows build its exception frame right below
 * rsp, overwriting the red zone: "Fault: read access to 0 at guest offset 0x28cf0d6", the first call
 * after the Fire Paper buff. Pre-touching the output pages (the previous attempt) cannot cover
 * every faulting access.
 *
 * Fix: each function is replaced by a relocated copy whose frame is 0x80 bytes bigger and whose
 * rsp displacements are all moved up by 0x80, so nothing lives below rsp. The blobs in
 * redzone_blobs.h are generated by tools/redzone_reloc.py (verified by tools/redzone_reloc_check.py).
 * At startup the original bytes are verified with FNV-1a-64, the blob is placed within rel32 reach
 * of the image (its rip-relative constants are fixed up), and the first 14 bytes of the original
 * function become `jmp [rip+0]` to the blob; the original body stays intact.
 * Always on (not a patches/Bloodborne.xml hook); BB_REDZONE_GUARD=0 disables it. Linux: no-op
 * (Linux signal frames skip the red zone). */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "hooks.h"
#include "runtime.h"
#ifdef _WIN32
#include <windows.h>
#endif

typedef struct { unsigned disp, end; unsigned long long target; } RzFixup;
typedef struct {
    unsigned long long start;
    unsigned size;
    unsigned long long fnv;
    const unsigned char *blob;
    unsigned blob_size;
    const RzFixup *fix;
    unsigned nfix;
} RzEntry;
#ifdef _WIN32
#include "redzone_blobs.h"

static const RzEntry rz_entries[] = {
    RZ_28CEEC0_ENTRY, RZ_28CE7B0_ENTRY, RZ_28CF580_ENTRY, RZ_28CFBA0_ENTRY,
};
#endif

#ifdef _WIN32
static uint64_t rz_fnv1a(const unsigned char *p, size_t n) {
    uint64_t h = 0xcbf29ce484222325ull;
    for (size_t i = 0; i < n; ++i) { h ^= p[i]; h *= 0x100000001b3ull; }
    return h;
}

/* Executable memory within +-1.75 GiB of `image` (a plain VirtualAlloc(NULL) can land farther away
 * than rel32 reaches), scanning outward from the image in 64 KiB steps. */
static unsigned char *rz_alloc_near(const unsigned char *image, size_t size) {
    const uint64_t reach = 0x70000000ull, base = (uint64_t)(uintptr_t)image & ~0xFFFFull;
    size = (size + 0xFFFF) & ~(size_t)0xFFFF;
    for (uint64_t step = 0x10000; step < reach; step += 0x10000) {
        const uint64_t tries[2] = {base - step, base + step};
        for (int k = 0; k < 2; ++k) {
            if (tries[k] < 0x10000 || tries[k] > 0x7FFFFFFF0000ull) continue;
            void *m = VirtualAlloc((void *)(uintptr_t)tries[k], size, MEM_RESERVE | MEM_COMMIT,
                                   PAGE_EXECUTE_READWRITE);
            if (m) return m;
        }
    }
    return NULL;
}

/* Builds the relocated copy of `e` for the eboot mapped at `image`: verifies the original bytes,
 * allocates the blob near the image, copies it and applies the rip fixups. Returns the blob or NULL
 * with *error set (a static string). Does not modify the image. */
unsigned char *redzone_guard_build(unsigned char *image, const RzEntry *e, const char **error) {
    if (rz_fnv1a(image + e->start, e->size) != e->fnv) { *error = "bytes differ"; return NULL; }
    unsigned char *blob = rz_alloc_near(image, e->blob_size);
    if (!blob) { *error = "no executable memory within 2 GiB of the image"; return NULL; }
    memcpy(blob, e->blob, e->blob_size);
    for (unsigned i = 0; i < e->nfix; ++i) {
        const RzFixup *f = &e->fix[i];
        int64_t d = (int64_t)((uint64_t)(uintptr_t)image + f->target) - (int64_t)(uintptr_t)(blob + f->end);
        if (d < INT32_MIN || d > INT32_MAX) {
            VirtualFree(blob, 0, MEM_RELEASE);
            *error = "rip fixup out of int32 range";
            return NULL;
        }
        int32_t d32 = (int32_t)d;
        memcpy(blob + f->disp, &d32, 4);
    }
    FlushInstructionCache(GetCurrentProcess(), blob, e->blob_size);
    return blob;
}

/* Overwrites the first 14 bytes at `site` with `jmp [rip+0]` + the absolute blob address. */
static int rz_patch_entry(unsigned char *site, const unsigned char *blob) {
    unsigned char jump[14] = {0xFF, 0x25, 0, 0, 0, 0};
    uint64_t target = (uint64_t)(uintptr_t)blob;
    memcpy(jump + 6, &target, 8);
    DWORD old;
    if (!VirtualProtect(site, sizeof jump, PAGE_EXECUTE_READWRITE, &old)) return 0;
    memcpy(site, jump, sizeof jump);
    DWORD ignored;
    VirtualProtect(site, sizeof jump, old, &ignored);
    FlushInstructionCache(GetCurrentProcess(), site, sizeof jump);
    return 1;
}
#endif

void runtime_redzone_guard_install(unsigned char *image) {
    const char *off = getenv("BB_REDZONE_GUARD");
    if (off && !strcmp(off, "0")) return;
#ifdef _WIN32
    for (size_t i = 0; i < sizeof rz_entries / sizeof rz_entries[0]; ++i) {
        const RzEntry *e = &rz_entries[i];
        const char *error = NULL;
        unsigned char *blob = redzone_guard_build(image, e, &error);
        if (!blob) {
            if (!strcmp(error, "bytes differ"))
                fprintf(stderr, "Red zone guard: 0x%x skipped (bytes differ)\n", (unsigned)e->start);
            else
                fprintf(stderr, "Red zone guard: 0x%x skipped (%s)\n", (unsigned)e->start, error);
            continue;
        }
        if (!rz_patch_entry(image + e->start, blob)) {
            fprintf(stderr, "Red zone guard: 0x%x skipped (cannot make the image text writable)\n", (unsigned)e->start);
            VirtualFree(blob, 0, MEM_RELEASE);
            continue;
        }
        fprintf(stderr, "Red zone guard: 0x%x -> relocated copy at %p (frame +0x80)\n", (unsigned)e->start, (void *)blob);
    }
#else
    (void)image; /* no red zone clobbering on Linux signals (they use the alternate/red-zone-safe frame) */
#endif
}
